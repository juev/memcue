test('one invocation delivers more than eight whole facts from one snapshot', async ($, on) => {
 on('env.get', () => ({value:undefined}))
 on('session.id', () => ({value:'native-case'}))
 on('session.cwd', () => ({value:'/synthetic'}))
 const facts = Array.from({length:12},(_,i)=>`Failure ${i}; `+'🙂 condition and workaround '.repeat(200))
 let reads=0
 on('process.run', () => { reads++; return {value:{exitCode:0,stdout:JSON.stringify({repository:'example.invalid/fixture',facts}),stderr:'',isStdoutTruncated:false,isStderrTruncated:false}} })
 on('classic.SessionStart', () => ({additionalContext:['existing context'],sessionTitle:'preserved'}))
 const result=await $.classic.SessionStart({hook_event_name:'SessionStart',session_id:'fixture',cwd:'/synthetic',source:'startup',transcript_path:''})
 expect(result.sessionTitle).toBe('preserved')
 for(const fact of facts) expect(result.additionalContext).toContain(fact)
 expect(reads).toBe(1)
})
